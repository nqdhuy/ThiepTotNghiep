let currentLanguage = 'vi';
const scene = document.querySelector('.letter-scene');
const envelope = document.querySelector('#open-letter');
const letter = document.querySelector('#letter');
const form = document.querySelector('#rsvp-form');
const message = document.querySelector('#form-message');
let isOpen = false;

function setLanguage(language) {
  currentLanguage = language;
  document.documentElement.lang = language;
  document.title = translations[language].pageTitle;
  document.querySelector('meta[name="description"]').content = translations[language].pageDescription;
  envelope.setAttribute('aria-label', translations[language].openLetterLabel);
  document.querySelector('#close-letter').setAttribute('aria-label', translations[language].closeLetterLabel);
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const value = translations[language][element.dataset.i18n];
    if (value) element.textContent = value;
  });
  document.querySelectorAll('[data-i18n-html]').forEach(element => {
    const value = translations[language][element.dataset.i18nHtml];
    if (value) element.innerHTML = value;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
    const value = translations[language][element.dataset.i18nPlaceholder];
    if (value) element.placeholder = value;
  });
  document.querySelectorAll('[data-lang]').forEach(button => {
    const active = button.dataset.lang === language;
    button.classList.toggle('active', active);
    button.setAttribute('aria-pressed', String(active));
  });
  message.textContent = '';
}

function openLetter() {
  if (isOpen) return;
  isOpen = true;
  scene.classList.add('has-open-letter');
  envelope.classList.add('open');
  letter.setAttribute('aria-hidden', 'false');
  letter.classList.add('open');
  window.setTimeout(() => {
    letter.querySelector('.close-letter').focus({ preventScroll: true });
    letter.scrollTop = 0;
  }, 1450);
}

function closeLetter() {
  if (!isOpen) return;
  isOpen = false;
  letter.classList.remove('open');
  letter.setAttribute('aria-hidden', 'true');
  scene.classList.remove('has-open-letter');
  envelope.classList.remove('open');
  envelope.focus();
}

envelope.addEventListener('click', openLetter);
document.querySelector('#close-letter').addEventListener('click', closeLetter);
document.querySelectorAll('[data-lang]').forEach(button => button.addEventListener('click', () => setLanguage(button.dataset.lang)));
document.addEventListener('keydown', event => { if (event.key === 'Escape') closeLetter(); });

form.addEventListener('submit', async event => {
  event.preventDefault();
  const data = new FormData(form);
  const wish = String(data.get('message') || '').trim();
  if (!wish) {
    message.className = 'form-message error';
    message.textContent = translations[currentLanguage].wishRequired;
    form.elements.message.focus();
    return;
  }
  const button = form.querySelector('button[type="submit"]');
  button.disabled = true;
  message.className = 'form-message';
  message.textContent = '';
  try {
    const response = await fetch('/api/rsvp', {
      method: 'POST', headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ name: data.get('name'), email: data.get('email'), guests: Number(data.get('guests')), attending: data.get('attending') === 'yes', message: wish })
    });
    if (!response.ok) {
      const key = response.status === 409 ? 'duplicate' : response.status === 422 ? 'invalid' : 'error';
      throw new Error(translations[currentLanguage][key]);
    }
    try {
      sessionStorage.setItem('rsvpName', String(data.get('name') || '').trim());
      sessionStorage.setItem('rsvpLanguage', currentLanguage);
      sessionStorage.setItem('rsvpAttending', data.get('attending') === 'yes' ? 'yes' : 'no');
    } catch { /* The thank-you page still works without personalization. */ }
    window.location.assign(`/thanks.html?lang=${currentLanguage}`);
  } catch (error) {
    message.textContent = error.message || translations[currentLanguage].error;
    message.classList.add('error');
  } finally {
    button.disabled = false;
  }
});
